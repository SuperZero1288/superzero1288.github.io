#!/usr/bin/env python3
"""Generate site/shapes.css: Material 3 Expressive style shapes as clip-path polygons.

Every shape has the same number of points, starting from the top and going clockwise,
so CSS can smoothly morph any shape into any other with a clip-path transition.
Usage: python scripts/build-shapes.py
"""
from __future__ import annotations

import math
from pathlib import Path

POINTS = 96
OUTPUT = Path(__file__).resolve().parent.parent / "site" / "shapes.css"


def rounded_polygon(sides: int, softness: float, turn: float = 0.0):
    def radius(theta: float) -> float:
        step = 2 * math.pi / sides
        local = (theta + turn) % step - step / 2
        return (1 - softness) * math.cos(math.pi / sides) / math.cos(local) + softness
    return radius


def superellipse(power: float):
    return lambda t: (abs(math.cos(t)) ** power + abs(math.sin(t)) ** power) ** (-1 / power)


SHAPES = {
    "circle": lambda t: 1.0,
    "square": superellipse(4.2),
    "cookie4": lambda t: 1 + 0.085 * math.cos(4 * t),
    "cookie6": lambda t: 1 + 0.07 * math.cos(6 * t),
    "cookie9": lambda t: 1 + 0.055 * math.cos(9 * t),
    "cookie12": lambda t: 1 + 0.04 * math.cos(12 * t),
    "clover4": lambda t: 0.6 + 0.4 * abs(math.cos(2 * t)) ** 0.55,
    "clover8": lambda t: 0.78 + 0.22 * abs(math.cos(4 * t)) ** 0.55,
    "flower": lambda t: 0.8 + 0.2 * abs(math.cos(4 * t)) ** 0.8,
    "burst": lambda t: 0.8 + 0.2 * (1 - abs(math.sin(6 * t))) ** 1.8,
    "pentagon": rounded_polygon(5, 0.24, math.pi / 2),
    "triangle": rounded_polygon(3, 0.3, math.pi / 2),
    "diamond": rounded_polygon(4, 0.22, math.pi / 2),
    "gem": rounded_polygon(6, 0.18, math.pi / 2),
}


def polygon(radius) -> str:
    angles = [-math.pi / 2 + 2 * math.pi * k / POINTS for k in range(POINTS)]
    raw = [(radius(a) * math.cos(a), radius(a) * math.sin(a)) for a in angles]
    xs, ys = [p[0] for p in raw], [p[1] for p in raw]
    scale = max(max(xs) - min(xs), max(ys) - min(ys))
    cx, cy = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
    points = [f"{50 + (x - cx) / scale * 100:.1f}% {50 + (y - cy) / scale * 100:.1f}%" for x, y in raw]
    return "polygon(" + ",".join(points) + ")"


def main() -> None:
    lines = ["/* Generated by scripts/build-shapes.py. Do not edit by hand. */", ":root{"]
    lines += [f"--shape-{name}:{polygon(radius)};" for name, radius in SHAPES.items()]
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(SHAPES)} shapes, {POINTS} points each -> {OUTPUT.name} ({OUTPUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
